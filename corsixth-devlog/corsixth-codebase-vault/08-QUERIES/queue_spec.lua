require("corsixth")
require("class_test_base")

require("queue")

local Queue = _G["Queue"]

local function makePatient()
  return {
    is_emergency = false,
    getRoom = function() return nil end,
    hospital = {
      hosp_cheats = {isCheatActive = function() return false end},
